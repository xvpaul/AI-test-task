#!/usr/bin/env bash
#
# Выполняется НА СЕРВЕРЕ после доставки конфига. Заливается через scp из deploy.yml.
#
# Задача: привести владельца каталога конфига к пользователю внутри контейнера
# и перезапустить сервис.
#
# Зачем chown: CI подключается под root, поэтому mkdir и scp создают файлы
# с владельцем root:root. Внутри образа процесс работает под пользователем node
# (обычно uid 1000) и не может писать в свой state-каталог — контейнер падает
# с EACCES на openclaw.sqlite-wal и уходит в цикл перезапусков.
#
# Переменные окружения (необязательные):
#   COMPOSE_DIR, OPENCLAW_DIR, OPENCLAW_IMAGE

set -euo pipefail
trap 'echo "ОШИБКА: строка ${LINENO}, код выхода $?" >&2' ERR

COMPOSE_DIR="${COMPOSE_DIR:-$HOME/openclaw}"
OPENCLAW_DIR="${OPENCLAW_DIR:-$HOME/.openclaw}"
OPENCLAW_IMAGE="${OPENCLAW_IMAGE:-ghcr.io/openclaw/openclaw:latest}"
COMPOSE_DIR="${COMPOSE_DIR/#\~/$HOME}"
OPENCLAW_DIR="${OPENCLAW_DIR/#\~/$HOME}"

SERVICE="openclaw-gateway"
cd "${COMPOSE_DIR}"

# --- Владелец каталога конфига ---------------------------------------------
# UID/GID спрашиваем у самого образа, а не хардкодим 1000: если сборка
# сменит пользователя, хардкод сломается молча.
echo "== Права на ${OPENCLAW_DIR} =="
if IDS="$(docker run --rm --entrypoint sh "${OPENCLAW_IMAGE}" -c 'id -u; id -g' 2>/dev/null | paste -sd: -)" \
   && [ "${IDS}" != ":" ] && [ -n "${IDS}" ]; then
  echo "пользователь внутри образа: ${IDS}"
else
  IDS="1000:1000"
  echo "не удалось спросить образ, беру значение по умолчанию: ${IDS}"
fi

# chown -R выполняем ВСЕГДА, без проверки «а вдруг уже правильно».
# Проверка по владельцу самого каталога была ошибкой: scp поверх
# существующего файла сохраняет inode и владельца, а новые файлы создаёт
# от root. Каталог при этом остаётся корректным, проверка проходит,
# и свежий root-овский файл остаётся незамеченным — ровно так конфиг
# и оказался недоступен процессу внутри контейнера.
echo "выставляю владельца ${IDS} на весь каталог"
chown -R "${IDS}" "${OPENCLAW_DIR}"

# Показать результат: если что-то опять не так, это будет видно в логе деплоя
echo "содержимое ${OPENCLAW_DIR}:"
ls -la "${OPENCLAW_DIR}" | sed 's/^/  /'

if find "${OPENCLAW_DIR}" -maxdepth 1 ! -user "${IDS%%:*}" -print -quit | grep -q .; then
  echo "НЕТ: остались файлы с чужим владельцем" >&2
  exit 1
fi

# --- Конфиг на месте? -------------------------------------------------------
# Шлюз читает строго ~/.openclaw/openclaw.json. Файл с любым другим именем
# молча игнорируется, шлюз стартует на дефолтах и падает с "Missing config".
CONFIG="${OPENCLAW_DIR}/openclaw.json"
if [ ! -f "${CONFIG}" ]; then
  echo "НЕТ: не найден ${CONFIG}" >&2
  echo "     Шлюз читает только это имя — проверьте шаг доставки конфига." >&2
  echo "     Содержимое каталога:" >&2
  ls -la "${OPENCLAW_DIR}" >&2
  exit 1
fi
echo "конфиг на месте: ${CONFIG} ($(wc -l < "${CONFIG}") строк)"

# Остаток от прежних деплоев под неправильным именем — только путает
rm -f "${OPENCLAW_DIR}/openclaw.config.json5"

# --- Перезапуск -------------------------------------------------------------
# --force-recreate, а не просто up -d, по трём причинам:
#   1. up -d при неизменившемся compose оставляет контейнер как есть
#      ("Container ... Running") — новый конфиг не перечитывается штатно;
#   2. RestartCount в Docker накопительный за всю жизнь контейнера, поэтому
#      проверка «сколько раз перезапустился» на старом контейнере бессмысленна;
#   3. сбрасывается restart-loop breaker шлюза, который после серии неудачных
#      стартов глушит автозапуск каналов (Telegram молчал бы и с валидным конфигом).
echo "== Пересоздание ${SERVICE} =="
docker compose up -d --force-recreate "${SERVICE}"

# --- Ожидание готовности ----------------------------------------------------
# Ждём по факту, а не фиксированным sleep: healthcheck может занять
# от пары секунд до полуминуты в зависимости от нагрузки VPS.
# Ждём строку готовности В ЛОГАХ, а не healthcheck Docker.
# Healthcheck этого образа надолго залипает в "starting" даже когда шлюз
# уже принимает сообщения, — по нему деплой ложно падал по таймауту.
echo "== Ожидание готовности (до 120 с) =="
deadline=$(( $(date +%s) + 120 ))
status=""
while [ "$(date +%s)" -lt "${deadline}" ]; do
  cid="$(docker compose ps -q "${SERVICE}")"
  [ -n "${cid}" ] || { sleep 3; continue; }

  running="$(docker inspect -f '{{.State.Running}}' "${cid}" 2>/dev/null || echo false)"
  # RestartCount осмысленен: контейнер только что пересоздан, счётчик с нуля
  restarts="$(docker inspect -f '{{.RestartCount}}' "${cid}" 2>/dev/null || echo 0)"

  # Логи берём по ID нового контейнера, без --since: контейнер только что
  # пересоздан, поэтому его лог и так содержит только текущий запуск.
  # Отсечка по времени была источником ошибки — Docker трактует строку
  # без суффикса Z как локальное время, и при не-UTC хосте окно уезжает.
  logs="$(docker logs "${cid}" 2>&1 || true)"

  # Перед сравнением снимаем ANSI-раскраску. Шлюз пишет теги в цвете, поэтому
  # в сырых байтах между "[gateway]" и "ready" стоят escape-последовательности.
  # В выводе деплоя и в терминале их не видно — строка выглядит обычной, но
  # буквального совпадения с "[gateway] ready" в ней нет. Ровно на этом молча
  # падали обе прошлые версии проверки: и `grep -q`, и сравнение через [[ ]].
  # Дело было не в пайпе.
  logs_plain="$(printf '%s\n' "${logs}" | sed 's/\x1b\[[0-9;]*[a-zA-Z]//g' || true)"

  # Сравниваем с обоими вариантами: если сборка перестанет красить вывод,
  # проверка продолжит работать.
  if [ "${running}" = "true" ] \
     && { [[ "${logs_plain}" == *"[gateway] ready"* ]] \
          || [[ "${logs}" == *"[gateway] ready"* ]]; }; then
    status="ok"; break
  fi
  if [ "${restarts}" -gt 3 ]; then
    status="crashloop"; break
  fi
  sleep 3
done

# Подтверждение, что персона на месте: молчаливое отсутствие файла
# означает бота с дефолтным характером вместо заданного
if [ -f "${OPENCLAW_DIR}/workspace/SOUL.md" ]; then
  echo "SOUL.md в workspace: да ($(wc -c < "${OPENCLAW_DIR}/workspace/SOUL.md") байт)"
else
  echo "ВНИМАНИЕ: ${OPENCLAW_DIR}/workspace/SOUL.md отсутствует — персона не применится" >&2
fi

echo
docker compose ps "${SERVICE}"
echo
echo "== Последние логи =="
docker compose logs --tail=40 "${SERVICE}"

case "${status}" in
  ok)
    echo
    echo "== Сервис поднялся =="
    ;;
  crashloop)
    echo
    echo "НЕТ: контейнер перезапускается циклически — смотрите логи выше" >&2
    exit 1
    ;;
  *)
    echo
    echo "НЕТ: за 120 с не появилась строка '[gateway] ready' в логах контейнера." >&2
    # Что именно видел цикл в последней итерации. Без этого прошлый ложный
    # таймаут пришлось разбирать вслепую: в логах строка была, а решение
    # принималось по данным, которых в выводе деплоя не оставалось.
    echo "     диагностика последней итерации:" >&2
    echo "       running=${running:-<нет>} restarts=${restarts:-<нет>} cid=${cid:-<нет>}" >&2
    echo "       строк в логах: $(printf '%s' "${logs:-}" | wc -l)" >&2
    if [[ "${logs_plain:-}" == *"[gateway] ready"* ]] || [[ "${logs:-}" == *"[gateway] ready"* ]]; then
      echo "       строка готовности В ЛОГАХ ЕСТЬ — значит сломана проверка, а не шлюз" >&2
    else
      echo "       буквального совпадения нет; строки со словом ready в сыром виде," >&2
      echo "       непечатаемые символы показаны как ^[ и M-:" >&2
      printf '%s\n' "${logs:-}" | grep -a 'ready' | cat -A | head -3 | sed 's/^/         /' >&2 || true
    fi
    exit 1
    ;;
esac
